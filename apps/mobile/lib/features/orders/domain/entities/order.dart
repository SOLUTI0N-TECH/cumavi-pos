import 'package:equatable/equatable.dart';

import '../../../../core/domain/payment_method.dart';

/// Where an online order stands (`ECO-R8`). `newOrder` is `new` in the API.
enum OrderStatus { newOrder, confirmed, ready, delivered, cancelled }

/// How the customer gets the order.
enum Fulfillment { pickup, delivery }

/// Where the order came from: the web catalog, or a WhatsApp message
/// imported by link while the API is not connected.
enum OrderSource { web, whatsappImport }

/// Snapshot of an ordered product: name and price are copied so the order
/// never changes if the catalog does.
final class OrderLine extends Equatable {
  const OrderLine({
    required this.productId,
    required this.productName,
    required this.unitPrice,
    required this.quantity,
    this.variantId,
    this.variantLabel,
  });

  final String productId;
  final String productName;
  final String? variantId;

  /// `Rojo · 40`
  final String? variantLabel;
  final double unitPrice;
  final int quantity;

  double get lineTotal => unitPrice * quantity;

  OrderLine withQuantity(int quantity) => OrderLine(
    productId: productId,
    productName: productName,
    variantId: variantId,
    variantLabel: variantLabel,
    unitPrice: unitPrice,
    quantity: quantity,
  );

  @override
  List<Object?> get props => <Object?>[
    productId,
    productName,
    variantId,
    variantLabel,
    unitPrice,
    quantity,
  ];
}

/// What the customer typed in the web checkout. No account is needed.
final class OrderCustomer extends Equatable {
  const OrderCustomer({
    required this.name,
    required this.phone,
    this.address = '',
    this.note = '',
  });

  final String name;

  /// National mobile number, 8 digits.
  final String phone;

  /// Required for delivery.
  final String address;

  /// Up to 200 characters.
  final String note;

  @override
  List<Object?> get props => <Object?>[name, phone, address, note];
}

/// One entry of the order's history (`order_status_history`).
final class OrderStatusChange extends Equatable {
  const OrderStatusChange({
    required this.to,
    required this.at,
    this.from,
    this.byName,
    this.note,
    this.isEdit = false,
  });

  /// `null` when the order was placed.
  final OrderStatus? from;
  final OrderStatus to;
  final DateTime at;

  /// Who changed it; `null` for the customer (placing the order).
  final String? byName;

  /// The cancel reason.
  final String? note;

  /// Lines or delivery fee changed; the state stayed the same.
  final bool isEdit;

  @override
  List<Object?> get props => <Object?>[from, to, at, byName, note, isEdit];
}

/// An order placed from the store's online catalog. It reaches the POS,
/// moves through its states and becomes a sale when it is charged.
final class Order extends Equatable {
  const Order({
    required this.id,
    required this.number,
    required this.createdAt,
    required this.status,
    required this.fulfillment,
    required this.customer,
    required this.paymentMethod,
    required this.lines,
    required this.publicToken,
    this.deliveryFee = 0,
    this.source = OrderSource.web,
    this.saleId,
    this.cancelReason,
    this.history = const <OrderStatusChange>[],
  });

  /// Generated by the web, so a retried order is never stored twice.
  final String id;

  /// Per business, from 1001 (`ECO-R7`).
  final int number;
  final DateTime createdAt;
  final OrderStatus status;
  final Fulfillment fulfillment;
  final OrderCustomer customer;
  final PaymentMethod paymentMethod;
  final List<OrderLine> lines;

  /// Set by the store when confirming a delivery; 0 by default.
  final double deliveryFee;
  final OrderSource source;

  /// Lets the customer follow the order without an account.
  final String publicToken;

  /// The sale created when the order was charged.
  final String? saleId;
  final String? cancelReason;

  /// Oldest first.
  final List<OrderStatusChange> history;

  /// `#1024`
  String get formattedNumber => '#$number';

  int get units =>
      lines.fold(0, (int total, OrderLine line) => total + line.quantity);

  double get subtotal =>
      lines.fold(0, (double total, OrderLine line) => total + line.lineTotal);

  double get total => subtotal + deliveryFee;

  /// Still needs the store's attention.
  bool get isOpen =>
      status != OrderStatus.delivered && status != OrderStatus.cancelled;

  bool get isDelivery => fulfillment == Fulfillment.delivery;

  Order copyWith({
    OrderStatus? status,
    List<OrderLine>? lines,
    double? deliveryFee,
    String? saleId,
    String? cancelReason,
    List<OrderStatusChange>? history,
  }) => Order(
    id: id,
    number: number,
    createdAt: createdAt,
    status: status ?? this.status,
    fulfillment: fulfillment,
    customer: customer,
    paymentMethod: paymentMethod,
    lines: lines ?? this.lines,
    publicToken: publicToken,
    deliveryFee: deliveryFee ?? this.deliveryFee,
    source: source,
    saleId: saleId ?? this.saleId,
    cancelReason: cancelReason ?? this.cancelReason,
    history: history ?? this.history,
  );

  @override
  List<Object?> get props => <Object?>[
    id,
    number,
    createdAt,
    status,
    fulfillment,
    customer,
    paymentMethod,
    lines,
    deliveryFee,
    source,
    publicToken,
    saleId,
    cancelReason,
    history,
  ];
}
